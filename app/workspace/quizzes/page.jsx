"use client"

import React, { useState, useEffect } from "react";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "../../../@/components/ui/card";
import { Button } from "../../../@/components/ui/button";
import { Badge } from "../../../@/components/ui/badge";
import { Skeleton } from "../../../@/components/ui/skeleton";
import { Input } from "../../../@/components/ui/input";
import { 
  Loader2, 
  AlertCircle, 
  RefreshCw, 
  FileQuestion, 
  Search, 
  Calendar,
  User,
  Target,
  Clock,
  Trash2,
  Eye
} from "lucide-react";
import { useUser } from "@clerk/nextjs";
import axios from "axios";
import { toast } from "sonner";

function Quizzes() {
    const [quizzes, setQuizzes] = useState([]);
    const [filteredQuizzes, setFilteredQuizzes] = useState([]);
    const [searchQuery, setSearchQuery] = useState("");
    const [isLoading, setIsLoading] = useState(false);
    const [error, setError] = useState(null);
    const [isAdmin, setIsAdmin] = useState(false);
    const { user } = useUser();

    useEffect(() => {
        user && GetAllQuizzes();
        user && checkAdminStatus();
    }, [user]);

    const checkAdminStatus = async () => {
        try {
            const response = await axios.get(`/api/admin/check?email=${user?.primaryEmailAddress?.emailAddress}`);
            if (response.data.success) {
                setIsAdmin(response.data.isAdmin);
            }
        } catch (error) {
            console.error('Error checking admin status:', error);
        }
    };

    useEffect(() => {
        // Filter quizzes based on search query
        if (searchQuery.trim() === "") {
            setFilteredQuizzes(quizzes);
        } else {
            const filtered = quizzes.filter(quiz => {
                const searchLower = searchQuery.toLowerCase();
                return (
                    quiz?.title?.toLowerCase().includes(searchLower) ||
                    quiz?.description?.toLowerCase().includes(searchLower) ||
                    quiz?.topic?.toLowerCase().includes(searchLower)
                );
            });
            setFilteredQuizzes(filtered);
        }
    }, [searchQuery, quizzes]);

    const GetAllQuizzes = async () => {
        try {
            setIsLoading(true);
            setError(null);
            const result = await axios.get('/api/quizzes');
            console.log('Quizzes:', result.data);
            if (result.data.success) {
                setQuizzes(result.data.quizzes);
                setFilteredQuizzes(result.data.quizzes);
            }
        } catch (error) {
            console.error('Error fetching quizzes:', error);
            setError('Failed to load quizzes. Please try again.');
        } finally {
            setIsLoading(false);
        }
    };

    const handleDeleteQuiz = async (quizId) => {
        if (!confirm('Are you sure you want to delete this quiz?')) return;

        try {
            const result = await axios.delete(`/api/quizzes?quizId=${quizId}`);
            if (result.data.success) {
                toast.success('Quiz deleted successfully');
                GetAllQuizzes();
            } else {
                toast.error(result.data.error || 'Failed to delete quiz');
            }
        } catch (error) {
            console.error('Error deleting quiz:', error);
            toast.error('Failed to delete quiz');
        }
    };

    const getDifficultyColor = (difficulty) => {
        const colors = {
            'easy': 'bg-emerald-100 text-emerald-800 dark:bg-emerald-900/30 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800',
            'medium': 'bg-amber-100 text-amber-800 dark:bg-amber-900/30 dark:text-amber-400 border border-amber-200 dark:border-amber-800',
            'hard': 'bg-rose-100 text-rose-800 dark:bg-rose-900/30 dark:text-rose-400 border border-rose-200 dark:border-rose-800'
        };
        return colors[difficulty] || colors.medium;
    };

    const formatDate = (dateString) => {
        try {
            const date = new Date(dateString);
            return date.toLocaleDateString('en-US', { 
                year: 'numeric', 
                month: 'short', 
                day: 'numeric',
                hour: '2-digit',
                minute: '2-digit'
            });
        } catch {
            return 'Unknown date';
        }
    };

    return (
        <div>
            <div className="flex items-center justify-between mb-6">
                <div>
                    <h2 className='font-bold text-3xl mb-2'>All Quizzes</h2>
                    <p className="text-muted-foreground">Browse and explore quizzes generated by all users</p>
                </div>
                <Button 
                    variant="outline" 
                    onClick={GetAllQuizzes}
                    disabled={isLoading}
                    className="flex items-center gap-2"
                >
                    <RefreshCw className={`h-4 w-4 ${isLoading ? 'animate-spin' : ''}`} />
                    Refresh
                </Button>
            </div>

            {/* Search Bar */}
            <div className='flex gap-3 max-w-2xl mb-6'>
                <div className="relative flex-1">
                    <Search className="absolute left-3 top-1/2 transform -translate-y-1/2 h-4 w-4 text-muted-foreground" />
                    <Input 
                        placeholder="Search quizzes by title, topic, or description..." 
                        value={searchQuery}
                        onChange={(e) => setSearchQuery(e.target.value)}
                        className="pl-10 h-12 text-base"
                    />
                </div>
            </div>

            {/* Loading State */}
            {isLoading && (
                <div className="space-y-4">
                    <div className="flex items-center gap-2 text-muted-foreground">
                        <Loader2 className="h-4 w-4 animate-spin" />
                        <span>Loading quizzes...</span>
                    </div>
                    <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
                        {[0,1,2,3,4,5].map((item, index) => (
                            <Skeleton key={index} className='w-full h-[280px] rounded-xl' />
                        ))}
                    </div>
                </div>
            )}

            {/* Error State */}
            {error && (
                <Card className="border-red-200 bg-red-50 dark:bg-red-950/20 dark:border-red-800">
                    <CardContent className="flex items-center gap-3 p-6">
                        <AlertCircle className="h-5 w-5 text-red-500" />
                        <div>
                            <h3 className="font-semibold text-red-700 dark:text-red-400">Error Loading Quizzes</h3>
                            <p className="text-sm text-red-600 dark:text-red-300">{error}</p>
                        </div>
                        <Button 
                            variant="outline" 
                            size="sm" 
                            onClick={GetAllQuizzes}
                            className="ml-auto"
                        >
                            Retry
                        </Button>
                    </CardContent>
                </Card>
            )}

            {/* Quizzes Content */}
            {!isLoading && !error && (
                <>
                    {/* Results Count */}
                    <div className="mb-4">
                        <p className="text-sm text-muted-foreground">
                            {searchQuery ? (
                                `Found ${filteredQuizzes.length} quiz${filteredQuizzes.length !== 1 ? 'zes' : ''} matching "${searchQuery}"`
                            ) : (
                                `Showing ${filteredQuizzes.length} quiz${filteredQuizzes.length !== 1 ? 'zes' : ''}`
                            )}
                        </p>
                    </div>

                    {/* No Quizzes */}
                    {filteredQuizzes.length === 0 && (
                        <Card className="border-dashed">
                            <CardContent className="flex flex-col items-center justify-center py-12 text-center">
                                <FileQuestion className="h-12 w-12 text-muted-foreground mb-4" />
                                <h3 className="text-lg font-semibold mb-2">No quizzes found</h3>
                                <p className="text-muted-foreground mb-4">
                                    {searchQuery ? 
                                        `No quizzes match your search "${searchQuery}". Try different keywords.` :
                                        "No quizzes have been generated yet. Generate your first quiz using the Quiz Generate AI tool!"
                                    }
                                </p>
                                {searchQuery && (
                                    <Button 
                                        variant="outline" 
                                        onClick={() => {
                                            setSearchQuery("");
                                            setFilteredQuizzes(quizzes);
                                        }}
                                    >
                                        Clear Search
                                    </Button>
                                )}
                            </CardContent>
                        </Card>
                    )}

                    {/* Quizzes Grid */}
                    {filteredQuizzes.length > 0 && (
                        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
                            {filteredQuizzes.map((quiz, index) => (
                                <Card key={quiz.quizId || index} className="hover:shadow-lg transition-shadow duration-300 border-2">
                                    <CardHeader className="pb-3">
                                        <div className="flex items-start justify-between gap-2 mb-2">
                                            <CardTitle className="text-lg line-clamp-2">
                                                {quiz.title}
                                            </CardTitle>
                                            <Badge className={`${getDifficultyColor(quiz.difficulty)} px-2 py-1 text-xs font-semibold`}>
                                                {quiz.difficulty}
                                            </Badge>
                                        </div>
                                        <CardDescription className="line-clamp-2">
                                            {quiz.description || "No description available"}
                                        </CardDescription>
                                    </CardHeader>
                                    <CardContent className="space-y-4">
                                        {/* Quiz Info */}
                                        <div className="space-y-2">
                                            <div className="flex items-center gap-2 text-sm text-muted-foreground">
                                                <Target className="h-4 w-4 text-blue-500" />
                                                <span className="font-medium">Topic:</span>
                                                <span className="text-foreground">{quiz.topic}</span>
                                            </div>
                                            <div className="flex items-center gap-2 text-sm text-muted-foreground">
                                                <FileQuestion className="h-4 w-4 text-purple-500" />
                                                <span className="font-medium">{quiz.questionCount} Questions</span>
                                            </div>
                                            <div className="flex items-center gap-2 text-sm text-muted-foreground">
                                                <User className="h-4 w-4 text-green-500" />
                                                <span className="text-xs truncate">{quiz.userEmail}</span>
                                            </div>
                                            <div className="flex items-center gap-2 text-sm text-muted-foreground">
                                                <Calendar className="h-4 w-4 text-orange-500" />
                                                <span className="text-xs">{formatDate(quiz.createdAt)}</span>
                                            </div>
                                        </div>

                                        {/* Actions */}
                                        <div className="flex gap-2 pt-2">
                                            <Button 
                                                variant="outline" 
                                                size="sm" 
                                                className="flex-1"
                                                onClick={() => {
                                                    // View quiz details (you can implement a modal or navigate to details page)
                                                    toast.info('Quiz details view coming soon!');
                                                }}
                                            >
                                                <Eye className="h-4 w-4 mr-2" />
                                                View
                                            </Button>
                                            {isAdmin && (
                                                <Button 
                                                    variant="outline" 
                                                    size="sm"
                                                    className="text-red-500 hover:text-red-700 hover:bg-red-50"
                                                    onClick={() => handleDeleteQuiz(quiz.quizId)}
                                                >
                                                    <Trash2 className="h-4 w-4" />
                                                </Button>
                                            )}
                                        </div>
                                    </CardContent>
                                </Card>
                            ))}
                        </div>
                    )}
                </>
            )}
        </div>
    );
}

export default Quizzes;

